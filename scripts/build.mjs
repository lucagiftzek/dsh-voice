#!/usr/bin/env node
/**
 * dsh-voice: browser-half build (same shape as dsh-phone's scripts/build.mjs).
 *
 * Bundles src/client/index.js -> lib/client.js wrapped in the
 * window.__ModuleLoader__.load({ id, factory }) call the web shell expects.
 *
 * format MUST be 'cjs': the factory returns module.exports. 'iife' leaves
 * module.exports empty and the WHOLE web UI fails to boot (that shipped once
 * elsewhere, 2026-09-19).
 *
 * JSX uses the classic React.createElement transform, so the bundle requires
 * exactly what the 1.x hand-written client required: 'react' and nothing else.
 *
 * lib/client.js is live once linked into a profile (the HMR watcher serves it to
 * the next page load). So the bundle is built in memory, loaded through a stub
 * __ModuleLoader__ and checked for { apply, inject, name } first, and only then
 * written to a temp file and renamed over lib/client.js: a failed or
 * half-written build never reaches the UI.
 *
 * Run: node scripts/build.mjs        (or: npm run build)
 *      node scripts/build.mjs --check (build and verify, write nothing)
 */
import { writeFileSync, renameSync, mkdirSync, readFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { runInNewContext } from 'node:vm'

const __dirname = dirname(fileURLToPath(import.meta.url))
const root = resolve(__dirname, '..')
const outfile = join(root, 'lib', 'client.js')
export const ID = '@lucagiftzek/dsh-voice'
export const EXPECTED_INJECT = '["slots"]'
export const EXPECTED_SLOTS = ['conversation.chat.assistant-actions:voice-speak', 'settings.section:voice-settings', 'conversation.input.right:voice-mic']

const banner = [
  '/* dsh-voice browser half: GENERATED by scripts/build.mjs from src/client. Do not edit. */',
  'window.__ModuleLoader__.load({',
  "  id: '@lucagiftzek/dsh-voice',",
  '  factory: function (require) {',
  '    var module = { exports: {} };',
  '    var exports = module.exports;',
].join('\n')
const footer = ['    return module.exports;', '  }', '});'].join('\n')

/** Load the bundle the way the web shell does and return what the factory exported. */
export function loadClientBundle(source) {
  let loaded
  const window = { __ModuleLoader__: { load: (entry) => { loaded = entry } } }
  runInNewContext(source, { window, console })
  if (!loaded || typeof loaded.factory !== 'function') throw new Error('bundle never called window.__ModuleLoader__.load({ id, factory })')
  const React = { createElement() { return null }, Fragment: 'Fragment', useState(v) { return [typeof v === 'function' ? v() : v, () => {}] }, useEffect() {}, useRef(v) { return { current: v } }, useMemo(f) { return f() }, useCallback(f) { return f } }
  const stubs = { react: React }
  const required = []
  const exported = loaded.factory((name) => {
    required.push(name)
    if (!(name in stubs)) throw new Error('bundle requires ' + JSON.stringify(name) + ', which the shell does not provide to this plugin')
    return stubs[name]
  })
  return { id: loaded.id, exported, required }
}

/** Throws unless the bundle keeps the 1.x contract: id, name, inject, apply, the three slots. */
export function verifyClientBundle(source) {
  if (source.includes('@deepseek-ai/')) throw new Error('client bundle purity: @deepseek-ai imports must not reach the client bundle')
  if (/[\u2013\u2014]/.test(source)) throw new Error('bundle contains an em or en dash')
  const { id, exported } = loadClientBundle(source)
  if (id !== ID) throw new Error('bundle registers id ' + JSON.stringify(id) + ', expected ' + JSON.stringify(ID))
  if (!exported || typeof exported.apply !== 'function') throw new Error('factory exports ' + JSON.stringify(Object.keys(exported || {})) + ' with no apply(): the web UI would not boot')
  if (exported.name !== 'dsh-voice') throw new Error('exported name is ' + JSON.stringify(exported.name))
  if (JSON.stringify(exported.inject) !== EXPECTED_INJECT) throw new Error('inject is ' + JSON.stringify(exported.inject) + ', expected ' + EXPECTED_INJECT)
  const seen = []
  const ctx = { slots: { inject: (slot, fn) => fn(), register: (meta, comp) => { if (typeof comp !== 'function') throw new Error('slot ' + meta.id + ' has no component'); seen.push(meta.name + ':' + meta.id); return () => {} } } }
  exported.apply(ctx)
  for (const s of EXPECTED_SLOTS) if (seen.indexOf(s) < 0) throw new Error('slot ' + s + ' is not registered')
  return { slots: seen }
}

export async function buildSource() {
  const { build } = await import('esbuild')
  const result = await build({
    entryPoints: [join(root, 'src', 'client', 'index.js')],
    bundle: true, outfile, write: false, format: 'cjs', platform: 'browser',
    target: ['chrome110', 'firefox110', 'safari16'],
    jsx: 'transform', jsxFactory: 'React.createElement', jsxFragment: 'React.Fragment',
    loader: { '.js': 'jsx', '.jsx': 'jsx' },
    charset: 'ascii',
    banner: { js: banner }, footer: { js: footer },
    external: ['react', 'react-dom'],
    minify: false, sourcemap: false, legalComments: 'none', logLevel: 'warning',
  })
  const source = result.outputFiles.find((f) => f.path === outfile)?.text
  if (!source) throw new Error('esbuild produced no ' + outfile)
  return source
}

async function main() {
  const source = await buildSource()
  const v = verifyClientBundle(source)
  if (process.argv.includes('--check')) {
    let same = false
    try { same = readFileSync(outfile, 'utf8') === source } catch (e) { same = false }
    console.log('dsh-voice: bundle verified (' + v.slots.length + ' slots); lib/client.js ' + (same ? 'is up to date' : 'is STALE, run npm run build'))
    if (!same) process.exit(2)
    return
  }
  mkdirSync(join(root, 'lib'), { recursive: true })
  const tmp = outfile + '.tmp-' + process.pid
  writeFileSync(tmp, source)
  renameSync(tmp, outfile)
  console.log('dsh-voice: bundle verified ({ apply, inject, name } and ' + v.slots.length + ' slots) and written to lib/client.js')
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((err) => {
    console.error('dsh-voice build failed, lib/client.js left untouched:', err.message || err)
    process.exit(1)
  })
}
